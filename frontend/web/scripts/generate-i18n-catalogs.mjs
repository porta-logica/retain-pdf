// Compiles the shared message catalogs in <repo>/locales/ into one typed TS module
// (src/platform/generated/i18n-catalogs.ts) that the web app imports.
//
// Why generate instead of importing JSON: the same module then works unchanged in esbuild,
// tsc and the node test loader, and the I18nKey union type gives compile errors for typos.
//
//   node scripts/generate-i18n-catalogs.mjs          write the module
//   node scripts/generate-i18n-catalogs.mjs --check  fail if the committed module is stale
//
// The pseudo-locale (languages.json "pseudo", e.g. "xx") is derived from the source language:
// every message is wrapped as "[!! … !!]" so any text that is still hardcoded stands out.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(here, "..");
const localesRoot = path.resolve(webRoot, "../../locales");
const outFile = path.join(webRoot, "src/platform/generated/i18n-catalogs.ts");

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

export function loadCatalogs(root = localesRoot) {
  const registry = readJson(path.join(root, "languages.json"));
  const catalogs = {};
  for (const { code } of registry.languages) {
    const dir = path.join(root, code);
    const messages = {};
    for (const file of fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
      Object.assign(messages, readJson(path.join(dir, file)));
    }
    catalogs[code] = messages;
  }
  return { registry, catalogs };
}

export function renderModule({ registry, catalogs }) {
  const source = catalogs[registry.source];
  const keys = Object.keys(source).sort();
  const sorted = (messages) =>
    Object.fromEntries(Object.keys(messages).sort().map((k) => [k, messages[k]]));
  const resources = {};
  for (const [code, messages] of Object.entries(catalogs)) resources[code] = sorted(messages);
  if (registry.pseudo) {
    resources[registry.pseudo] = Object.fromEntries(keys.map((k) => [k, `[!! ${source[k]} !!]`]));
  }
  const languages = registry.languages.map(({ code, name }) => ({ code, name }));
  return [
    "// Generated by scripts/generate-i18n-catalogs.mjs from <repo>/locales/. Do not edit by hand.",
    "/* eslint-disable */",
    `export const SOURCE_LANGUAGE = ${JSON.stringify(registry.source)} as const;`,
    `export const PSEUDO_LANGUAGE = ${JSON.stringify(registry.pseudo || null)};`,
    `export const LANGUAGES = ${JSON.stringify(languages, null, 2)} as const;`,
    "export type LanguageCode = (typeof LANGUAGES)[number][\"code\"];",
    "export type I18nKey =",
    ...keys.map((k, i) => `  | ${JSON.stringify(k)}${i === keys.length - 1 ? ";" : ""}`),
    `export const RESOURCES: Record<string, Record<string, string>> = ${JSON.stringify(resources, null, 2)};`,
    "",
  ].join("\n");
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const text = renderModule(loadCatalogs());
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : "";
    if (current !== text) {
      console.error(`${path.relative(process.cwd(), outFile)} is stale; run: npm run generate:i18n`);
      process.exit(1);
    }
  } else {
    fs.mkdirSync(path.dirname(outFile), { recursive: true });
    fs.writeFileSync(outFile, text);
    console.log(`i18n catalogs generated: ${path.relative(process.cwd(), outFile)}`);
  }
}
